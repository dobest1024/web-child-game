export function lessonKey(course, index) {
  return `${course.id}:${course.stages[index].id ?? index}`;
}
export function migrateProgress(completed, courses) {
  const legacy = ["cross-aligned", "f2l-right", "oll-sune", "pll-t"];
  const valid = new Set(
    courses.flatMap((c) => c.stages.map((_, i) => lessonKey(c, i))),
  );
  return [
    ...new Set(
      (Array.isArray(completed) ? completed : [])
        .map((key) => {
          const match = /^cfop:([0-3])$/.exec(key);
          return match ? `cfop:${legacy[Number(match[1])]}` : key;
        })
        .filter((key) => valid.has(key)),
    ),
  ];
}
export function lessonStep(lesson, index) {
  let offset = 0;
  for (const [i, group] of lesson.groups.entries()) {
    const count = group.moves.split(" ").length;
    if (index < offset + count)
      return {
        ...group,
        groupIndex: i,
        within: index - offset + 1,
        count,
        start: offset,
      };
    offset += count;
  }
  return null;
}
