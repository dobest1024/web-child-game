const group = (moves, title, why) => ({ moves, title, why });
function lesson(
  id,
  chapter,
  name,
  intro,
  recognition,
  groups,
  check,
  extra = {},
) {
  const hold =
    "白色中心朝下，黄色中心朝上，绿色中心朝自己。对照初始图，过程中不换整颗魔方的拿法。";
  return {
    id,
    chapter,
    name,
    intro,
    recognition,
    hold,
    groups,
    alg: groups.map((g) => g.moves).join(" "),
    goal: check,
    check,
    tip: "先核对形状和侧面颜色。公式中途可能暂时打乱已完成的部分，请把整组做完再检查。",
    narration: `${intro}${hold}${recognition}${check}`,
    ...extra,
  };
}
