function parseCharRow(row) {
  const [c, ids, py, word, emoji, source] = row.split('|');
  const layout = ids[0] === '⿰' ? 'lr' : 'tb';
  return { c, parts: [...ids.slice(1)], layout, py, word, emoji, source };
}
